import { expect, test } from '@playwright/test'

test('v1 desktop list/detail layout keeps search, filters and drafts usable', async ({ page }) => {
  await page.setViewportSize({width: 1680, height: 1050})
  await page.goto('/')
  await page.getByRole('button', {name: 'Organization administrator', exact: true}).click()
  await page.getByText('Replay events', {exact: true}).click()
  await page.getByRole('button', {name: 'Reset playground', exact: true}).click()
  await page.getByRole('button', {name: 'Platform analyst', exact: true}).click()
  const filters = page.getByRole('complementary', {name: 'Review filters', exact: true})
  await expect(filters).toBeVisible()
  await page.getByRole('button', {name: 'CVE-2099-20001', exact: true}).click()
  const detail = page.getByRole('region', {name: 'CVE-2099-20001', exact: true})
  await expect(detail).toBeVisible()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(filters).toBeHidden()
  await detail.getByLabel('Reason and evidence', {exact: true}).fill('Draft preserved while browsing the findings queue.')
  await page.getByRole('button', {name: 'CVE-2099-20002', exact: true}).click()
  await expect(page.getByRole('region', {name: 'CVE-2099-20002', exact: true})).toBeVisible()
  await page.getByRole('button', {name: 'CVE-2099-20001', exact: true}).click()
  await expect(detail.getByLabel('Reason and evidence', {exact: true})).toHaveValue('Draft preserved while browsing the findings queue.')
  await page.getByRole('button', {name: 'Filters', exact: true}).click()
  await expect(filters).toBeVisible()
  await expect(page.getByLabel('Search', {exact: true})).toBeEditable()
  await expect.poll(async () => page.getByRole('button', {name: 'Filters', exact: true}).getAttribute('aria-expanded')).toBe('true')
  const bounds = await detail.boundingBox()
  expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(1050)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({path: '/tmp/dtvp-v1-layout-restored.png', fullPage: true})
  await page.setViewportSize({width: 390, height: 844})
  const dialog = page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  await expect(dialog.getByLabel('Reason and evidence', {exact: true})).toHaveValue('Draft preserved while browsing the findings queue.')
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
})
