import { expect, test } from '@playwright/test'
import { beginAssessment, confirmDraft, confirmReview } from './workflow'

test('real import, assessment, approval, snapshot, revalidation, and team isolation', async ({ page }) => {
  test.setTimeout(60000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByRole('button', { name: 'Organization administrator', exact: true }).click()
  await page.getByText('Replay events', { exact: true }).click()
  await page.getByRole('button', { name: 'Reset playground', exact: true }).click()
  await page.getByRole('button', { name: 'Platform analyst', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Review workspace' })).toBeVisible()
  await page.getByRole('button', { name: 'Products', exact: true }).click()
  await page.getByText('Import SBOM', { exact: true }).locator('input').setInputFiles('../playground/fixtures/release.cdx.json')
  await expect(page.getByRole('status')).toContainText('SBOM imported')
  await page.getByRole('button', { name: 'Edit metadata' }).first().click()
  await page.getByRole('dialog').getByLabel('Responsible team').fill('Platform')
  await page.getByRole('dialog').getByRole('button', { name: 'Save metadata' }).click()
  await expect(page.getByRole('status')).toContainText('Metadata saved')
  await page.getByRole('button', { name: 'Review', exact: true }).click()
  await page.getByRole('button', { name: 'CVE-2099-20001', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.getByRole('heading', { name: 'CVE-2099-20001' })).toBeVisible()
  await expect(dialog.getByRole('button', { name: 'Close finding' })).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(dialog.getByRole('button', { name: 'Refresh evidence', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'CVE-2099-20001', exact: true })).toBeFocused()
  await page.keyboard.press('Enter')
  await beginAssessment(page)
  await dialog.getByLabel('Reason and evidence').fill('Synthetic exposure confirmed. Upgrade planned.')
  await dialog.getByLabel('Applicability').selectOption('affected')
  await confirmDraft(page)
  await dialog.getByRole('button', { name: 'Submit assessment' }).click()
  await expect(dialog.getByRole('status')).toContainText('Decision saved')
  await dialog.getByRole('button', { name: 'Close finding' }).click()
  await page.getByLabel('Persona').selectOption('reviewer')
  await page.getByRole('button', { name: 'CVE-2099-20001', exact: true }).click()
  await confirmReview(page)
  await dialog.getByRole('button', { name: 'Approve decision' }).click()
  await expect(dialog.getByRole('status')).toContainText('approved')
  await dialog.getByRole('button', { name: 'Close finding' }).click()
  await page.getByRole('button', { name: 'Products', exact: true }).click()
  await page.getByRole('button', { name: 'Create snapshot' }).click()
  await expect(page.getByRole('link', { name: 'VScorer vulnerability list' })).toBeVisible()
  const worklistUrl = await page.getByRole('link', { name: 'VScorer vulnerability list' }).getAttribute('href')
  const worklist = await (await page.request.get(worklistUrl!)).json()
  expect(worklist.cves).toHaveLength(2)
  await page.getByLabel('Persona').selectOption('analyst')
  await page.getByText('Replay events', { exact: true }).click()
  await page.getByRole('button', { name: 'Changed evidence' }).click()
  await page.getByRole('button', { name: 'Review', exact: true }).click()
  await expect(page.locator('tbody').getByText('Evidence changed', { exact: true }).first()).toBeVisible()
  await page.getByLabel('Theme').selectOption('dark')
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.getByLabel('Persona').selectOption('operations')
  await expect(page.getByRole('button', { name: 'CVE-2099-20001', exact: true })).toHaveCount(0)
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByRole('heading', { name: 'Review workspace' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.getByRole('button', { name: 'Products', exact: true }).click()
  await page.getByText('Matching and advisory services', { exact: true }).click()
  await page.getByRole('combobox', { name: 'Provider', exact: true }).selectOption('demo')
  await page.getByRole('button', { name: 'Run selected provider' }).click()
  await page.getByRole('button', { name: 'Activity', exact: true }).click()
  await expect(page.getByText('succeeded', { exact: true })).toBeVisible({ timeout: 15000 })
  await page.getByRole('button', { name: 'Review', exact: true }).click()
  await page.getByRole('button', { name: 'Refresh', exact: true }).click()
  await expect(page.getByRole('button', { name: 'CVE-2099-20003', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Products', exact: true }).click()
  await page.getByText('Matching and advisory services', { exact: true }).click()
  await page.getByRole('combobox', { name: 'Provider', exact: true }).selectOption('demo-failure')
  await page.getByRole('button', { name: 'Run selected provider' }).click()
  await page.getByRole('button', { name: 'Activity', exact: true }).click()
  await expect(page.getByText('Simulated source timeout; coverage remains unknown', { exact: true })).toBeVisible({ timeout: 15000 })
  expect(errors).toEqual([])
})
