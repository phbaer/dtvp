import { expect, test } from '@playwright/test'
import { confirmDraft, confirmReview } from './workflow'

test('rescoring waits for team approval and belongs to the coordinator', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Organization administrator', exact: true }).click()
  await page.getByText('Replay events', { exact: true }).click()
  await page.getByRole('button', { name: 'Reset playground', exact: true }).click()
  await page.getByRole('button', { name: 'Organization administrator', exact: true }).click()
  const me = await (await page.request.get('/api/v2/me')).json()
  const project = (await (await page.request.get('/api/v2/projects')).json()).find((p: {name: string}) => p.name === 'Demo Gateway')
  const operations = me.workspaces.find((w: {name: string}) => w.name === 'Operations')
  const csrf = (await page.context().cookies()).find(cookie => cookie.name === 'dtvp_csrf')!.value
  const shared = await page.request.put(`/api/v2/projects/${project.id}/sharing`, {headers: {'X-CSRF-Token': csrf}, data: {workspace_id: operations.id, capabilities: ['read', 'assess', 'approve', 'evidence']}})
  expect(shared.ok()).toBe(true)
  await page.getByRole('button', { name: 'CVE-2099-20001', exact: true }).click()
  await page.getByRole('dialog').getByRole('tab', { name: 'Teams & scoring', exact: true }).click()
  await page.getByRole('button', { name: 'Change required teams', exact: true }).click()
  await page.getByRole('checkbox', { name: 'Operations', exact: true }).check()
  await page.getByRole('button', { name: 'Save required teams', exact: true }).click()
  await expect(page.locator('.team-reviews li')).toHaveCount(2)
  await page.getByRole('button', { name: 'Close finding', exact: true }).click()
  await page.getByRole('combobox', { name: 'Persona', exact: true }).selectOption('coordinator')
  await page.getByRole('button', { name: 'CVE-2099-20001', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('tab', { name: 'Teams & scoring', exact: true }).click()
  await expect(dialog.getByText('Waiting for required team reviews.', { exact: true })).toBeVisible()
  await expect(dialog.getByRole('checkbox', { name: /Include contextual CVSS score/ })).toHaveCount(0)
  await dialog.getByRole('button', { name: 'Close finding', exact: true }).click()
  await page.getByRole('combobox', { name: 'Persona', exact: true }).selectOption('analyst')
  await page.getByRole('button', { name: 'CVE-2099-20001', exact: true }).click()
  await dialog.getByRole('combobox', { name: 'Applicability', exact: true }).selectOption('not_affected')
  await dialog.getByRole('combobox', { name: 'Why not affected?', exact: true }).selectOption('code_not_reachable')
  await dialog.getByLabel('Reason and evidence', { exact: true }).fill('Deployment evidence proves the vulnerable path cannot be reached.')
  await confirmDraft(page)
  await dialog.getByRole('button', { name: 'Submit assessment', exact: true }).click()
  await expect(dialog.getByRole('status')).toContainText('Decision saved')
  await dialog.getByRole('button', { name: 'Close finding', exact: true }).click()
  await page.getByRole('combobox', { name: 'Persona', exact: true }).selectOption('reviewer')
  await page.getByRole('button', { name: 'CVE-2099-20001', exact: true }).click()
  await confirmReview(page)
  await dialog.getByRole('button', { name: 'Approve decision', exact: true }).click()
  await expect(dialog.getByRole('status')).toContainText('approved')
  await dialog.getByRole('button', { name: 'Close finding', exact: true }).click()
  await page.getByRole('combobox', { name: 'Persona', exact: true }).selectOption('coordinator')
  await page.getByRole('button', { name: 'CVE-2099-20001', exact: true }).click()
  await dialog.getByRole('tab', { name: 'Teams & scoring', exact: true }).click()
  await expect(dialog.getByText('Waiting for required team reviews.', { exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: 'Close finding', exact: true }).click()
  await page.getByRole('combobox', { name: 'Persona', exact: true }).selectOption('operations')
  await page.getByRole('button', { name: 'CVE-2099-20001', exact: true }).click()
  await dialog.getByRole('combobox', { name: 'Applicability', exact: true }).selectOption('not_affected')
  await dialog.getByRole('combobox', { name: 'Why not affected?', exact: true }).selectOption('protected_at_runtime')
  await dialog.getByLabel('Reason and evidence', { exact: true }).fill('Operations verified runtime protection for this deployment.')
  await confirmDraft(page)
  await dialog.getByRole('button', { name: 'Submit assessment', exact: true }).click()
  await expect(dialog.getByRole('status')).toContainText('Decision saved')
  await dialog.getByRole('button', { name: 'Close finding', exact: true }).click()
  await page.getByRole('combobox', { name: 'Persona', exact: true }).selectOption('operations-reviewer')
  await page.getByRole('button', { name: 'CVE-2099-20001', exact: true }).click()
  await confirmReview(page)
  await dialog.getByRole('button', { name: 'Approve decision', exact: true }).click()
  await expect(dialog.getByRole('status')).toContainText('approved')
  await dialog.getByRole('button', { name: 'Close finding', exact: true }).click()
  await page.getByRole('combobox', { name: 'Persona', exact: true }).selectOption('coordinator')
  await page.getByRole('button', { name: 'CVE-2099-20001', exact: true }).click()
  await dialog.getByRole('tab', { name: 'Teams & scoring', exact: true }).click()
  await expect(dialog.locator('.team-reviews li .badge')).toHaveText(['approved', 'approved'])
  await dialog.getByRole('checkbox', { name: /Include contextual CVSS score/ }).check()
  await dialog.getByLabel('Context and scoring rationale', { exact: true }).fill('All required team reviews completed; apply the project applicability rule.')
  await dialog.getByRole('button', { name: 'Preview contextual score', exact: true }).click()
  await expect(dialog.getByText('Preview ready', { exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: 'Publish contextual score', exact: true }).click()
  await expect(dialog.getByRole('heading', { name: 'Published contextual score', exact: true })).toBeVisible()
  await expect(dialog.getByRole('button', { name: 'Publish contextual score', exact: true })).toBeDisabled()
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})
