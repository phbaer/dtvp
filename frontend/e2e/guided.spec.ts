import { expect, test } from '@playwright/test'
import { beginAssessment } from './workflow'

test('analysts assess applicability with evidence and independent review, without rescoring', async ({ page }) => {
  await page.goto('/?page=Review')
  await page.getByRole('button', { name: 'Organization administrator', exact: true }).click()
  await page.getByText('Replay events', { exact: true }).click()
  await page.getByRole('button', { name: 'Reset playground', exact: true }).click()
  await page.getByRole('button', { name: 'Platform analyst', exact: true }).click()
  await page.getByRole('button', { name: 'CVE-2099-20001', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect.poll(async () => dialog.evaluate(node => node.getBoundingClientRect().height / window.innerHeight)).toBeLessThan(0.8)
  await expect(dialog.getByRole('heading', { name: 'Evidence at a glance' })).toBeVisible()
  await expect(dialog.getByRole('heading', { name: 'Your assessment', exact: true })).toBeVisible()
  await expect(dialog.getByRole('navigation', { name: 'Assessment progress' }).getByRole('button', { name: '2 Confirm' })).toBeDisabled()
  await beginAssessment(page)
  await expect(dialog.getByRole('button', { name: 'Review and confirm' })).toBeDisabled()
  await dialog.getByLabel('Reason and evidence').fill('Verified deployment boundaries and remediation plan.')
  await dialog.getByLabel('Applicability').selectOption('affected')
  await expect(dialog.getByRole('checkbox', { name: /Include contextual CVSS score/ })).toHaveCount(0)
  await dialog.getByRole('button', { name: 'Review and confirm' }).click()
  await dialog.getByRole('button', { name: 'Back', exact: true }).click()
  await expect(dialog.getByLabel('Reason and evidence')).toHaveValue('Verified deployment boundaries and remediation plan.')
  await dialog.getByRole('button', { name: 'Review and confirm' }).click()
  await expect(dialog.getByRole('heading', { name: 'Ready for independent review' })).toBeVisible()
  await expect(dialog.getByRole('complementary', { name: 'Finding evidence' }).getByRole('heading', { name: 'Evidence at a glance' })).toBeVisible()
  await expect(dialog.getByRole('heading', { name: 'Contextual severity' })).toHaveCount(0)
  await dialog.getByRole('button', { name: 'Submit assessment', exact: true }).click()
  await expect(dialog.getByRole('status')).toContainText('Decision saved')
  await dialog.getByRole('button', { name: 'Close finding', exact: true }).click()
  await page.getByRole('combobox', { name: 'Persona', exact: true }).selectOption('reviewer')
  await page.getByRole('button', { name: 'CVE-2099-20001', exact: true }).click()
  await beginAssessment(page)
  await expect(dialog.getByRole('heading', { name: 'Latest assessment', exact: true })).toBeVisible()
  await expect(dialog.getByRole('button', { name: 'Approve decision', exact: true })).toHaveCount(0)
  await dialog.getByRole('button', { name: 'Review and confirm' }).click()
  await expect(dialog.getByRole('button', { name: 'Approve decision', exact: true })).toBeDisabled()
  await dialog.getByRole('checkbox', { name: 'I checked applicability and supporting evidence.', exact: true }).check()
  await expect(dialog.getByRole('button', { name: 'Approve decision', exact: true })).toBeEnabled()
  await page.setViewportSize({ width: 390, height: 844 })
  await dialog.getByRole('button', { name: /^Evidence ·/ }).click()
  await expect(dialog.getByRole('heading', { name: 'Evidence at a glance' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await dialog.getByRole('button', { name: 'Approve decision', exact: true }).click()
  await expect(dialog.getByRole('status')).toContainText('approved')
})
