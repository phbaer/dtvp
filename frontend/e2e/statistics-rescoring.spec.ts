import { expect, test } from '@playwright/test'
import { beginAssessment } from './workflow'

test('statistics, applicability review and original severity retention', async ({ page }) => {
  test.setTimeout(60000)
  await page.goto('/')
  await page.getByRole('button', { name: 'Organization administrator', exact: true }).click()
  await page.getByText('Replay events', { exact: true }).click()
  await page.getByRole('button', { name: 'Reset playground', exact: true }).click()
  await page.getByRole('button', { name: 'Platform analyst', exact: true }).click()
  await page.getByRole('button', { name: 'Statistics', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Statistics', exact: true })).toBeVisible()
  await expect(page.locator('.stat-cards article').filter({ hasText: 'Component / release findings' }).locator('strong')).toHaveText('2')
  const teams = page.getByRole('heading', { name: 'Owning teams', exact: true }).locator('..')
  await teams.getByRole('row').filter({ hasText: 'Platform' }).getByRole('button', { name: '2', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Review workspace', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'CVE-2099-20001', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.getByRole('heading', { name: 'Evidence at a glance' })).toBeVisible()
  await beginAssessment(page)
  await expect(dialog.getByRole('heading', { name: 'Your assessment', exact: true })).toBeVisible()
  await expect(dialog.getByRole('tab', { name: 'Assessment & review', exact: true })).toHaveAttribute('aria-selected', 'true')
  await dialog.getByRole('combobox', { name: 'Applicability', exact: true }).selectOption('not_affected')
  await dialog.getByRole('combobox', { name: 'Why not affected?', exact: true }).selectOption('code_not_reachable')
  await dialog.getByLabel('Reason and evidence', { exact: true }).fill('Release scope and deployment controls verified.')
  await expect(dialog.getByRole('checkbox', { name: /Include contextual CVSS score/ })).toHaveCount(0)
  await dialog.getByRole('button', { name: 'Review and confirm', exact: true }).click()
  await dialog.getByRole('button', { name: 'Submit assessment', exact: true }).click()
  await expect(dialog.getByRole('status')).toContainText('Decision saved')
  await beginAssessment(page)
  await expect(dialog.getByRole('heading', { name: 'Proposed contextual score', exact: true })).toHaveCount(0)
  await dialog.getByRole('button', { name: 'Close finding', exact: true }).click()
  await page.getByRole('combobox', { name: 'Persona', exact: true }).selectOption('reviewer')
  await page.getByRole('combobox', { name: 'Status', exact: true }).selectOption('ready')
  await page.getByRole('button', { name: 'CVE-2099-20001', exact: true }).click()
  await beginAssessment(page)
  await expect(dialog.getByRole('heading', { name: 'Latest assessment', exact: true })).toBeVisible()
  await expect(dialog.getByRole('heading', { name: 'Your assessment', exact: true })).toHaveCount(0)
  await dialog.getByRole('button', { name: 'Review and confirm', exact: true }).click()
  await dialog.getByRole('checkbox', { name: 'I checked applicability and supporting evidence.', exact: true }).check()
  await dialog.getByRole('button', { name: 'Approve decision', exact: true }).click()
  await expect(dialog.getByRole('status')).toContainText('approved')
  await beginAssessment(page)
  await expect(dialog.getByRole('heading', { name: 'Approved contextual score', exact: true })).toHaveCount(0)
  await dialog.getByRole('tab', { name: 'Evidence & history', exact: true }).click()
  await expect(dialog.getByRole('heading', { name: 'Evidence and decision history', exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: 'Close finding', exact: true }).click()
  await page.getByRole('combobox', { name: 'Status', exact: true }).selectOption('')
  await page.getByRole('button', { name: 'Statistics', exact: true }).click()
  const severity = page.getByRole('heading', { name: 'Severity distribution', exact: true }).locator('..')
  await expect(severity.getByRole('row').filter({ hasText: 'none' })).toContainText('0')
  await page.getByRole('button', { name: 'Reset scope', exact: true }).click()
  await page.getByRole('combobox', { name: 'Persona', exact: true }).selectOption('operations')
  await expect(page.locator('.stat-cards article').filter({ hasText: 'Component / release findings' }).locator('strong')).toHaveText('1')
  await expect(page.locator('.stat-cards article').filter({ hasText: 'Projects with findings' }).locator('small')).toHaveText('1 projects in scope')
  await expect(page.getByRole('heading', { name: 'Owning teams', exact: true }).locator('..').getByRole('row').filter({ hasText: 'Platform' })).toHaveCount(0)
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})
