import { expect, test } from '@playwright/test'

test('previous DTVP metadata and plain DT documentation remain usable', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Organization administrator', exact: true }).click()
  await page.getByText('Replay events', { exact: true }).click()
  await page.getByRole('button', { name: 'Reset playground', exact: true }).click()
  await page.getByRole('button', { name: 'Platform analyst', exact: true }).click()
  await page.getByRole('button', { name: 'Products', exact: true }).click()
  await page.getByText('Import SBOM', { exact: true }).locator('input').setInputFiles('../playground/fixtures/legacy-dt.cdx.json')
  await expect(page.getByRole('status')).toContainText('SBOM imported')
  await page.getByRole('button', { name: 'Review', exact: true }).click()
  await expect(page.locator('tbody').getByText('Legacy assessment', { exact: true })).toHaveCount(2)
  await page.getByRole('button', { name: 'CVE-2099-20001', exact: true }).click()
  let dialog = page.getByRole('dialog')
  await expect(dialog.getByText(/Previous DTVP documentation/)).toBeVisible()
  await expect(dialog.getByText('The HTTP feature is not built in this release.', { exact: true })).toBeVisible()
  await expect(dialog.getByText(/Source assessor: Alice/)).toBeVisible()
  await expect(dialog.getByText(/Source reviewer: Bob/)).toBeVisible()
  await expect(dialog.getByText(/Legacy contextual score: 4/)).toBeVisible()
  await expect(dialog.getByLabel('Reason and evidence')).toHaveValue('The HTTP feature is not built in this release.')
  await expect(dialog.locator('.score')).toHaveText('9.8')
  await dialog.getByRole('button', { name: 'Close finding' }).click()
  await page.getByRole('button', { name: 'CVE-2099-20002', exact: true }).click()
  dialog = page.getByRole('dialog')
  await expect(dialog.getByText(/Legacy documentation without DTVP metadata/)).toBeVisible()
  await expect(dialog.getByText('Assessor not recorded', { exact: true })).toBeVisible()
  await expect(dialog.getByLabel('Reason and evidence')).toHaveValue('Legacy parser review: untrusted files reach the parser. Patch required.')
  await expect(dialog.getByRole('button', { name: 'Approve decision' })).toHaveCount(0)
})
