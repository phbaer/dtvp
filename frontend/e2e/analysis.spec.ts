import { expect, test } from '@playwright/test'

test('Agentyzer simulation offers explicit drafts, follow-ups and coverage failures', async ({ page }) => {
  test.setTimeout(60000)
  await page.goto('/')
  await page.getByRole('button', { name: 'Organization administrator', exact: true }).click()
  await page.getByText('Replay events', { exact: true }).click()
  await page.getByRole('button', { name: 'Reset playground', exact: true }).click()
  await page.getByRole('button', { name: 'Platform analyst', exact: true }).click()
  await page.getByRole('button', { name: 'CVE-2099-20001', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('tab', { name: 'Analysis', exact: true }).click()
  await expect(dialog.getByRole('heading', { name: 'Agentyzer code analysis' })).toBeVisible()
  await dialog.getByRole('button', { name: 'Run code analysis', exact: true }).click()
  await expect(dialog.getByText('Synthetic code analysis: reachable dependency.', { exact: true })).toBeVisible({ timeout: 15000 })
  await dialog.getByRole('tab', { name: 'Assessment & review', exact: true }).click()
  await expect(dialog.getByLabel('Reason and evidence')).toHaveValue('')
  await dialog.getByRole('tab', { name: 'Analysis', exact: true }).click()
  await dialog.getByRole('button', { name: 'Use proposal in draft', exact: true }).click()
  await expect(dialog.getByLabel('Applicability')).toHaveValue('affected')
  await expect(dialog.getByLabel('Reason and evidence')).toHaveValue(/Playground evidence only/)
  await expect(dialog.getByRole('heading', { name: 'Latest assessment', exact: true })).toHaveCount(0)
  await dialog.getByRole('tab', { name: 'Analysis', exact: true }).click()
  await dialog.getByRole('button', { name: 'View full analysis report', exact: true }).click()
  await expect(dialog.locator('pre').first()).toContainText('application_eligible')
  await dialog.getByText('Ask a follow-up', { exact: true }).click()
  await dialog.getByLabel('Follow-up question').fill('Does the worker expose this path?')
  await dialog.getByRole('button', { name: 'Submit follow-up', exact: true }).click()
  await expect(dialog.getByText('Synthetic code analysis: reachable dependency.', { exact: true })).toHaveCount(2, { timeout: 15000 })
  await dialog.getByText('Analysis options', { exact: true }).click()
  await dialog.getByLabel('Simulated outcome').selectOption('inconclusive')
  await dialog.getByRole('button', { name: 'Run code analysis', exact: true }).click()
  await expect(dialog.getByText('Synthetic code analysis: source coverage is incomplete.', { exact: true })).toBeVisible({ timeout: 15000 })
  await expect(dialog.getByRole('button', { name: 'Use proposal in draft', exact: true })).toHaveCount(0)
  await dialog.getByLabel('Simulated outcome').selectOption('failure')
  await dialog.getByRole('button', { name: 'Run code analysis', exact: true }).click()
  await expect(dialog.getByText(/Simulated Agentyzer failure; existing decisions remain unchanged/)).toBeVisible({ timeout: 15000 })
  await dialog.getByRole('tab', { name: 'Assessment & review', exact: true }).click()
  await expect(dialog.getByLabel('Reason and evidence')).toHaveValue(/Playground evidence only/)
})
