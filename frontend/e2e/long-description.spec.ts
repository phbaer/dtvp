import { expect, test } from '@playwright/test'
import { readFileSync } from 'node:fs'

test('long vulnerability evidence stays readable while recording a not-affected reason', async ({ page }) => {
  await page.goto('/?page=Review')
  await page.getByRole('button', { name: 'Organization administrator', exact: true }).click()
  await page.getByText('Replay events', { exact: true }).click()
  await page.getByRole('button', { name: 'Reset playground', exact: true }).click()
  await page.getByRole('button', { name: 'Platform analyst', exact: true }).click()
  await page.getByRole('button', { name: 'Products', exact: true }).click()
  const bom = JSON.parse(readFileSync('../playground/fixtures/release.cdx.json', 'utf8'))
  const description = Array.from({ length: 35 }, (_, i) => `Deployment context paragraph ${i + 1}. ${'Evidence about code paths and verified configuration. '.repeat(8)}`).join('\n\n')
  bom.vulnerabilities[0].description = description
  const upload = page.getByText('Import SBOM', { exact: true }).locator('input')
  await expect(upload).toBeEnabled()
  await upload.setInputFiles({ name: 'long-description.cdx.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(bom)) })
  await expect(page.getByRole('status')).toContainText('SBOM imported')
  await page.getByRole('button', { name: 'Review', exact: true }).click()
  await page.getByRole('button', { name: 'CVE-2099-20001', exact: true }).click()
  const dialog = page.getByRole('dialog'), evidence = dialog.getByRole('complementary', { name: 'Finding evidence' })
  await expect(dialog).toHaveClass(/roomy/)
  await evidence.getByRole('combobox', { name: 'Description source', exact: true }).selectOption({ label: 'file' })
  await expect(evidence.locator('.finding-description')).toHaveText(description)
  await evidence.evaluate(node => { node.scrollTop = node.scrollHeight })
  expect(await evidence.evaluate(node => node.scrollHeight > node.clientHeight)).toBe(true)
  await expect(dialog.getByLabel('Reason and evidence')).toBeInViewport()
  await expect(dialog.getByRole('button', { name: 'Review and confirm', exact: true })).toBeInViewport()
  await dialog.getByRole('combobox', { name: 'Applicability', exact: true }).selectOption('not_affected')
  await dialog.getByLabel('Reason and evidence').fill('Disabled route verified in the release configuration and integration test.')
  await expect(dialog.getByRole('button', { name: 'Review and confirm', exact: true })).toBeDisabled()
  await dialog.getByRole('combobox', { name: 'Why not affected?', exact: true }).selectOption('requires_configuration')
  await evidence.evaluate(node => { node.scrollTop = 0 })
  await page.screenshot({ path: '/tmp/dtvp-long-review.png' })
  await dialog.getByRole('button', { name: 'Review and confirm', exact: true }).click()
  await expect(dialog.locator('.confirmation').getByText('Required configuration is absent', { exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: 'Submit assessment', exact: true }).click()
  await expect(dialog.getByRole('status')).toContainText('Decision saved')
  await expect(dialog.locator('.assessment-summary .justification')).toHaveText('Required configuration is absent')
  await dialog.getByRole('button', { name: 'Use compact view', exact: true }).click()
  await expect(dialog).not.toHaveClass(/roomy/)
  await dialog.getByRole('button', { name: 'Expand review', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await dialog.getByRole('button', { name: /^Evidence ·/ }).click()
  await expect(evidence.locator('.finding-description')).toHaveText(description)
})
