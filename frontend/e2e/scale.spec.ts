import { expect, test } from '@playwright/test'

test('large inventory stays searchable and review context survives navigation', async ({ page }) => {
  test.setTimeout(120000)
  await page.goto('/?page=Review')
  if (await page.getByLabel('Persona').count()) await page.getByLabel('Persona').selectOption('administrator')
  else await page.getByRole('button', { name: 'Organization administrator', exact: true }).click()
  await page.getByText('Replay events', { exact: true }).click()
  await page.getByRole('button', { name: 'Reset playground', exact: true }).click()
  await page.getByRole('button', { name: 'Organization administrator', exact: true }).click()
  await page.getByText('Replay events', { exact: true }).click()
  await page.getByRole('button', { name: 'Load large inventory', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('100 synthetic projects', { timeout: 60000 })
  await page.getByRole('button', { name: 'Products', exact: true }).click()
  await page.getByRole('button', { name: 'Product Demo Gateway', exact: true }).click()
  await page.getByRole('combobox', { name: 'Search product', exact: true }).fill('0100')
  await page.getByRole('option', { name: 'Scale product 0100 Platform', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Product Scale product 0100', exact: true })).toBeVisible()
  await page.getByLabel('Search components', { exact: true }).fill('0019')
  await page.getByRole('button', { name: 'Search components', exact: true }).click()
  await expect(page.getByRole('cell', { name: 'scale-library-0019', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Review', exact: true }).click()
  await page.getByRole('button', { name: 'Review product All', exact: true }).click()
  await page.getByRole('combobox', { name: 'Search review product', exact: true }).fill('0100')
  await page.getByRole('option', { name: 'Scale product 0100 Platform', exact: true }).click()
  await expect(page.locator('tbody tr')).toHaveCount(20)
  await page.getByRole('button', { name: 'CVE-2099-30000', exact: true }).click()
  await page.getByRole('button', { name: 'Next finding', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'CVE-2099-30001', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Close finding' }).click()
  await page.getByText('More filters and saved views', { exact: true }).click()
  await page.getByLabel('View name', { exact: true }).fill('Scale review')
  await page.getByRole('button', { name: 'Save view', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Scale review', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Reset filters', exact: true }).click()
  await page.getByRole('button', { name: 'Scale review', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Review product Scale product 0100', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.locator('tbody tr')).toHaveCount(20)
  await expect(page.getByRole('button', { name: 'Review product Scale product 0100', exact: true })).toBeVisible()
  await page.getByLabel('Persona').selectOption('operations')
  await expect(page.getByRole('button', { name: 'CVE-2099-20003', exact: true })).toBeVisible()
  await expect(page.locator('tbody').getByText('Scale product 0100', { exact: true })).toHaveCount(0)
  await page.getByText('More filters and saved views', { exact: true }).click()
  await page.getByRole('button', { name: 'Reset filters', exact: true }).click()
  await expect(page.locator('tbody').getByText('Scale product 0100', { exact: true })).toHaveCount(0)
})
